#!/usr/bin/env python3
"""Generate runtime text pins from the maintained asset manifest."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    path = ROOT / "profiles/flash-next-text-assets.json"
    manifest = json.loads(path.read_bytes())
    model_digest = hashlib.sha256(
        (ROOT / "profiles/flash-next-assets.json").read_bytes()
    ).hexdigest()
    if manifest["model_asset_manifest_sha256"] != model_digest:
        raise ValueError("text manifest model digest is stale")
    tokenizer = manifest["tokenizer"]["sha256"]
    template = manifest["chat_template"]["sha256"]
    for value in (tokenizer, template):
        if len(value) != 64 or any(c not in "0123456789abcdef" for c in value):
            raise ValueError("invalid text asset SHA-256")
    notice = "Generated by scripts/generate_text_pins.py from profiles/flash-next-text-assets.json."
    return {
        ROOT
        / "rust/crates/tokspur-text/src/assets.rs": f'//! {notice}\n\npub const TOKENIZER_SHA256: &str =\n    "{tokenizer}";\npub const TEMPLATE_SHA256: &str =\n    "{template}";\n',
        ROOT
        / "native/include/tokspur/text_assets.hpp": f'// {notice}\n#pragma once\n\nnamespace tokspur::text_assets {{\ninline constexpr char tokenizer_sha256[] = "{tokenizer}";\ninline constexpr char template_sha256[] = "{template}";\n}}\n',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"stale generated text pins: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()

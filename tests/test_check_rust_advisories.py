#!/usr/bin/env python3
"""Exercise the OSV Rust advisory check offline with canned OSV responses.

Adapted from the over-show app's scripts/tests/test_check_rust_advisories.py at
commit ecabf371a (SHA-256 785c14d5b4415c593c4f9cac85aaabb9d207acd954314278e10b33774898c921).
"""

from __future__ import annotations

import importlib.util
import io
import shutil
import tempfile
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "check_rust_advisories.py"
SPEC = importlib.util.spec_from_file_location("check_rust_advisories", SCRIPT)
advisories = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(advisories)

CRATES_IO = advisories.CRATES_IO


def lockfile(*packages: tuple[str, str, str | None]) -> str:
    blocks = ["# This file is automatically @generated by Cargo.\nversion = 4\n"]
    for name, version, source in packages:
        block = f'[[package]]\nname = "{name}"\nversion = "{version}"\n'
        if source:
            block += f'source = "{source}"\n'
        blocks.append(block)
    return "\n".join(blocks)


def record(
    identifier: str,
    *,
    aliases=(),
    informational=None,
    withdrawn=None,
    fixed=None,
    summary="summary",
):
    affected = {"package": {"name": "crate", "ecosystem": "crates.io"}, "ranges": []}
    if fixed:
        affected["ranges"] = [
            {"type": "SEMVER", "events": [{"introduced": "0"}, {"fixed": fixed}]}
        ]
    if informational:
        affected["database_specific"] = {"informational": informational}
    result = {
        "id": identifier,
        "aliases": list(aliases),
        "summary": summary,
        "affected": [affected],
    }
    if withdrawn:
        result["withdrawn"] = withdrawn
    return result


class FakeOsv:
    def __init__(
        self, hits: dict[tuple[str, str], list[str]], records: dict[str, dict]
    ):
        self.hits = hits
        self.records = records
        self.batches = 0

    def __call__(self, url: str, body: dict | None) -> dict:
        if url == advisories.OSV_BATCH:
            self.batches += 1
            return {
                "results": [
                    {
                        "vulns": [
                            {"id": identifier}
                            for identifier in self.hits.get(
                                (query["package"]["name"], query["version"]), []
                            )
                        ]
                    }
                    for query in body["queries"]
                ]
            }
        identifier = url.rsplit("/", 1)[1]
        return self.records[identifier]


class RustAdvisoryCheckTests(unittest.TestCase):
    def repository(self, audit: str, lock: str) -> Path:
        directory = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, directory, ignore_errors=True)
        config = directory / advisories.AUDIT_CONFIG
        config.parent.mkdir(parents=True)
        config.write_text(audit)
        for relative in advisories.LOCKFILES:
            path = directory / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(lock)
        return directory

    def test_locked_packages_keeps_only_crates_io(self):
        text = lockfile(
            ("serde", "1.0.229", CRATES_IO),
            ("tokspur-json", "0.1.0", None),
            (
                "fix-path-env",
                "0.0.0",
                "git+https://github.com/tauri-apps/fix-path-env-rs?rev=c4c45d5#c4c45d5",
            ),
        )
        self.assertEqual(advisories.locked_packages(text), {("serde", "1.0.229")})

    def test_ignored_advisories_reads_the_list_and_skips_comments(self):
        text = '[advisories]\n# "RUSTSEC-2000-0001" stays commented\nignore = [\n    "RUSTSEC-2023-0071", # rsa\n    "GHSA-aaaa-bbbb-cccc",\n]\n\n[output]\nquiet = false\n'
        self.assertEqual(
            advisories.ignored_advisories(text),
            {"RUSTSEC-2023-0071", "GHSA-aaaa-bbbb-cccc"},
        )

    def test_vulnerability_fails_and_names_the_fix(self):
        root = self.repository(
            "[advisories]\nignore = []\n", lockfile(("tauri", "2.10.3", CRATES_IO))
        )
        fake = FakeOsv(
            {("tauri", "2.10.3"): ["GHSA-7gmj-67g7-phm9"]},
            {"GHSA-7gmj-67g7-phm9": record("GHSA-7gmj-67g7-phm9", fixed="2.11.1")},
        )
        out = io.StringIO()
        self.assertEqual(advisories.check(root, fake, out), 1)
        self.assertIn(
            "error    GHSA-7gmj-67g7-phm9: tauri 2.10.3 in rust/Cargo.lock",
            out.getvalue(),
        )
        self.assertIn("fixed in 2.11.1", out.getvalue())

    def test_alias_twins_report_once_and_informational_twin_only_warns(self):
        root = self.repository(
            "[advisories]\nignore = []\n", lockfile(("rand", "0.7.3", CRATES_IO))
        )
        fake = FakeOsv(
            {("rand", "0.7.3"): ["GHSA-cq8v-f236-94qc", "RUSTSEC-2026-0097"]},
            {
                "GHSA-cq8v-f236-94qc": record(
                    "GHSA-cq8v-f236-94qc", aliases=["RUSTSEC-2026-0097"]
                ),
                "RUSTSEC-2026-0097": record(
                    "RUSTSEC-2026-0097",
                    aliases=["GHSA-cq8v-f236-94qc"],
                    informational="unsound",
                ),
            },
        )
        out = io.StringIO()
        self.assertEqual(advisories.check(root, fake, out), 0)
        lines = [
            line for line in out.getvalue().splitlines() if line.startswith("warning")
        ]
        self.assertEqual(len(lines), 1)
        self.assertIn("GHSA-cq8v-f236-94qc, RUSTSEC-2026-0097", lines[0])

    def test_ignore_matches_any_alias(self):
        root = self.repository(
            '[advisories]\nignore = ["RUSTSEC-2023-0071"]\n',
            lockfile(("rsa", "0.9.10", CRATES_IO)),
        )
        fake = FakeOsv(
            {("rsa", "0.9.10"): ["GHSA-c38w-74pg-36hr"]},
            {
                "GHSA-c38w-74pg-36hr": record(
                    "GHSA-c38w-74pg-36hr",
                    aliases=["RUSTSEC-2023-0071", "CVE-2023-49092"],
                )
            },
        )
        out = io.StringIO()
        self.assertEqual(advisories.check(root, fake, out), 0)
        self.assertIn("ignored  GHSA-c38w-74pg-36hr", out.getvalue())

    def test_withdrawn_advisory_is_skipped(self):
        root = self.repository(
            "[advisories]\nignore = []\n", lockfile(("demo", "1.0.0", CRATES_IO))
        )
        fake = FakeOsv(
            {("demo", "1.0.0"): ["GHSA-wwww-xxxx-yyyy"]},
            {
                "GHSA-wwww-xxxx-yyyy": record(
                    "GHSA-wwww-xxxx-yyyy", withdrawn="2026-01-01T00:00:00Z"
                )
            },
        )
        out = io.StringIO()
        self.assertEqual(advisories.check(root, fake, out), 0)
        self.assertNotIn("GHSA-wwww-xxxx-yyyy", out.getvalue())

    def test_withdrawn_informational_alias_does_not_hide_active_vulnerability(self):
        root = self.repository(
            "[advisories]\nignore = []\n", lockfile(("demo", "1.0.0", CRATES_IO))
        )
        fake = FakeOsv(
            {("demo", "1.0.0"): ["GHSA-active", "RUSTSEC-withdrawn"]},
            {
                "GHSA-active": record("GHSA-active", aliases=["RUSTSEC-withdrawn"]),
                "RUSTSEC-withdrawn": record(
                    "RUSTSEC-withdrawn",
                    aliases=["GHSA-active"],
                    informational="unsound",
                    withdrawn="2026-01-01T00:00:00Z",
                ),
            },
        )
        out = io.StringIO()
        self.assertEqual(advisories.check(root, fake, out), 1)
        self.assertIn("error    GHSA-active, RUSTSEC-withdrawn", out.getvalue())

    def test_batches_are_split_at_the_osv_limit(self):
        packages = [
            (f"crate{index}", "1.0.0", CRATES_IO)
            for index in range(advisories.BATCH_SIZE + 5)
        ]
        root = self.repository("[advisories]\nignore = []\n", lockfile(*packages))
        fake = FakeOsv({}, {})
        self.assertEqual(advisories.check(root, fake, io.StringIO()), 0)
        self.assertEqual(fake.batches, 2 * len(advisories.LOCKFILES))

    def test_mismatched_batch_response_is_an_error(self):
        root = self.repository(
            "[advisories]\nignore = []\n", lockfile(("serde", "1.0.229", CRATES_IO))
        )

        def short(url, body):
            return {"results": []}

        with self.assertRaises(advisories.CheckError):
            advisories.check(root, short, io.StringIO())

    def test_missing_lockfile_is_an_error(self):
        root = self.repository(
            "[advisories]\nignore = []\n", lockfile(("serde", "1.0.229", CRATES_IO))
        )
        (root / advisories.LOCKFILES[-1]).unlink()
        with self.assertRaises(advisories.CheckError):
            advisories.check(root, FakeOsv({}, {}), io.StringIO())


if __name__ == "__main__":
    unittest.main()
